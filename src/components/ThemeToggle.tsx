// 다크모드 ↔ 화이트모드. **「도구 ▾」 메뉴의 맨 아랫줄**이고, 누를 때마다 뒤집힌다.
//
// ⚠️⚠️⚠️ **자리를 아홉 번 옮기고 여기로 왔다. 옮기자는 말이 나오면 이 주석부터 읽을 것.**
//    「도구 ▾」안 → 사람 아이콘 왼쪽 → 메뉴 맨 앞 → 로고 옆 → 메뉴 맨 오른쪽 끝 →
//    마이페이지에 따로 → 계정 카드의 로그인 단추 옆 → 마이페이지 제목 줄 →
//    오른쪽 아래 떠 있는 단추 → **「도구 ▾」 맨 아래(제자리로 돌아옴)**.
//
//    **머리말에 뒀던 네 자리가 다 퇴짜맞은 까닭은 자리가 아니라 성격이었다.**
//    머리말 줄에 있는 것은 전부 **누르면 다른 화면으로 가는** 것이다(홈·도감·도구·
//    커뮤니티·마이페이지). 화면 색 단추만 어디로도 안 간다 — 길 안내 줄에 길이 아닌
//    것이 껴 있으니 왼쪽에 두든 오른쪽에 두든 계속 걸렸다. **자리를 옮겨서는 안 풀린다.**
//
//    ⚠️ **떠 있는 단추(FAB)는 이 사이트에서 못 쓴다.** 아래쪽 가장자리에 이미 셋이
//       깔려 있다 — 카드 상세 시트 · 비교 담기 바 · 카드 뽑기 하단 바(전부 bottom-0).
//       실측: 카드를 열어 놓고 단추 자리를 찍으니 **거기 있는 것은 시세 그래프**였다.
//       사람들이 제일 오래 머무는 화면에서 아예 안 눌린다. z를 올려 덮으면 이번엔
//       카드 그림·그래프 위에 동그라미가 얹힌다.
//    ⚠️ 처음에 여기 뒀다가 **「머리말에 40px 자리가 없다」고 잘못 재서** 꺼냈던 것이다.
//       자리가 있다는 건 거기 있어야 할 이유가 아니다.
//
// ⚠️⚠️ **글자·아이콘 모두 「지금」이 아니라 「누르면 갈 곳」을 가리킨다.** 화이트모드로
//    보고 있으면 달(=어둡게)이 뜨고 「다크모드」라고 적힌다. 지금 무엇인지는 화면 색이
//    이미 말하고 있다.
// ⚠️ 낱말은 사장님이 고른 그대로 쓴다(다크모드·화이트모드). 이 리포는 화면 문구를
//    「어두운 화면」처럼 우리말로 풀어 쓰지만, 이 둘은 지시받은 것이다.
// ⚠️ 설명 글을 붙이지 말 것 — 두 낱말이 곧 설명이다. 제목+설명 두 줄로 만들었다가
//    퇴짜맞았고, 두 칸짜리 토글(다크모드|화이트모드)도 「하나만 쓰라」고 다시 지시받았다.
//
// ⚠️ 색을 바꾸는 일은 CSS가 한다(index.css의 「어두운 화면」 절). 여기는 `<html>`의
//    표시만 붙였다 뗀다. 색 클래스는 한 줄도 안 건드린다.
import { useEffect, useState } from 'react';
import { 테마바르기, 지금어두운가 } from '../lib/theme';

export function ThemeToggle({ onDone }: { onDone?: () => void }) {
  const [어두움, set어두움] = useState<boolean>(() => 지금어두운가());
  // ⚠️ 아직 한 번도 안 고른 사람은 **기기 설정을 따라간다.** 폰이 밤에 어두워지면 같이 바뀐다.
  useEffect(() => {
    const mq = window.matchMedia('(prefers-color-scheme: dark)');
    const 다시 = () => set어두움(지금어두운가());
    mq.addEventListener('change', 다시);
    return () => mq.removeEventListener('change', 다시);
  }, []);

  const 이름 = 어두움 ? '화이트모드' : '다크모드';
  return (
    <button
      type="button"
      onClick={() => {
        // 지금 보이는 것의 **반대**로 간다. 「기기 설정 따라가기」에서 눌러도 눈에 보이는
        // 대로 바뀌는 게 단추 하나를 누른 사람이 기대하는 결과다.
        const 다음 = 어두움 ? 'light' : 'dark';
        테마바르기(다음);
        set어두움(다음 === 'dark');
        onDone?.(); // 누르면 메뉴를 닫는다 — 다른 항목과 같은 몸짓이다
      }}
      // ⚠️ 아이콘이 붙어 있어도 이름을 남긴다 — 화면 읽기 프로그램에는 색이 안 보인다.
      aria-label={`${이름}로 바꾸기`}
      // ⚠️ 옆 항목(오늘의 상점·팝수·센터링)과 **글자 크기·여백을 그대로** 맞춘다.
      //    아이콘 자리는 `gap`으로만 벌린다 — 항목마다 들여쓰기가 다르면 줄이 어긋나 보인다.
      className="flex w-full items-center gap-2 px-4 py-2 text-left text-sm font-semibold text-neutral-600 hover:bg-neutral-50"
    >
      {어두움 ? (
        // 해 — 누르면 밝아진다
        <svg className="h-4 w-4" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" aria-hidden>
          <circle cx="12" cy="12" r="4" />
          <path
            strokeLinecap="round"
            d="M12 2v2M12 20v2M4.9 4.9l1.4 1.4M17.7 17.7l1.4 1.4M2 12h2M20 12h2M4.9 19.1l1.4-1.4M17.7 6.3l1.4-1.4"
          />
        </svg>
      ) : (
        // 달 — 누르면 어두워진다
        <svg className="h-4 w-4" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" aria-hidden>
          <path strokeLinecap="round" strokeLinejoin="round" d="M21 12.8A9 9 0 1 1 11.2 3a7 7 0 0 0 9.8 9.8z" />
        </svg>
      )}
      {이름}
    </button>
  );
}
