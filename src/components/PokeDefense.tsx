/**
 * 도트 그림의 **빈 여백** [위, 아래, 왼, 오른] — 0~1 몫이다.
 *
 * ⚠️⚠️ 왜 필요한가: PokéAPI 도트는 전부 96×96인데 **포켓몬이 차지하는 자리가 제각각**이다
 *    (실측: 위 여백이 적게는 5%, 많게는 39% · 가운데 23%). 그대로 그리면
 *    ①작은 포켓몬은 **땅에서 붕 떠서** 걷고 ②체력 바가 머리 위 한참에 뜬다.
 *    2026-08-18에 사장님 화면에서 둘 다 보였다.
 * ⚠️ 값은 `scripts/measure-dot-trim.mts`가 잰다(꾸러미 없이 zlib으로 PNG를 읽는다).
 *    **도트를 새로 받으면 그 스크립트도 다시 돌릴 것.**
 * ⚠️ 크기는 **고르게 안 맞춘다** — 잠만보가 캐터피보다 큰 것은 그림이 그렇게 그려진 것이고
 *    그게 맞다. 여기서 고치는 것은 「어디에 서 있나」뿐이다.
 */
const 기본여백: [number, number, number, number] = [0.2, 0.2, 0.2, 0.2];
function 도트여백(id: number): [number, number, number, number] {
  // ⚠️ JSON에서 온 배열은 타입이 `number[]`라 튜플로 바로 못 본다 — 길이를 확인하고 짓는다.
  const v = (여백표 as Record<string, number[]>)[String(id)];
  return v && v.length === 4 ? [v[0], v[1], v[2], v[3]] : 기본여백;
}

function 글자색(바탕: string): string {
  const m = /^#?([0-9a-f]{6})$/i.exec(바탕.trim());
  if (!m) return '#fff';
  const n = parseInt(m[1], 16);
  // sRGB → 상대 밝기(WCAG). 사람 눈이 느끼는 밝기가 아니라 **대비를 재는 자**다.
  const 선형 = (v: number) => {
    const c = v / 255;
    return c <= 0.03928 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4);
  };
  const L = 0.2126 * 선형((n >> 16) & 255) + 0.7152 * 선형((n >> 8) & 255) + 0.0722 * 선형(n & 255);
  // 어두운 글씨는 순검정이 아니라 #1a1a1a다(이 앱의 제일 진한 글씨). 그 밝기가 0.01034.
  const 검대비 = (L + 0.05) / (0.01034 + 0.05);
  const 흰대비 = 1.05 / (L + 0.05);
  return 검대비 >= 흰대비 ? '#1a1a1a' : '#fff';
}

