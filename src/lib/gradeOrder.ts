// 감정 등급을 화면에 세우는 순서. **서버와 화면이 이 한 벌만 쓴다.**
//
// 왜 따로 뺐나: 같은 규칙을 서버(api.ts)와 화면(api/ebayPrices.ts)이 각각 들고 있었다.
// 2026-08-07에 등급 순서를 바꾸면서 그 순서에 기대던 곳 셋이 조용히 깨진 적이 있고
// (추이 그래프·검색 타일·비교표), 고치는 과정에서 규칙이 또 두 벌이 됐다.
// 두 벌이면 언젠가 한쪽만 고쳐서 같은 자료를 화면마다 다르게 세우게 된다.
//
// ⚠️ 이 파일은 **아무것도 가져오지 않는다.** 서버가 가져다 쓰기 때문이다
//    (api/ebayPrices.ts는 이름 사전을 끌고 와서 서버에 넣으면 안 된다).
//    새 import를 넣기 전에 서버가 그걸 감당할 수 있는지 볼 것.
// ⚠️ 서버가 이 파일을 쓰므로 **Dockerfile COPY 목록에도 있어야 한다.**
//    `npm run build`의 배포 파일 검사가 빠뜨리면 알려 준다.

// 감정 기관을 세우는 차례. PSA가 가장 많이 쓰이니 먼저다.
const 기관우선 = ['psa', 'bgs', 'cgc', 'sgc', 'tag'];

/**
 * 등급 하나의 자리값. 작을수록 위에 온다.
 *
 * ⚠️⚠️ **`ungraded`는 맨 아래로 내렸다**(2026-08-15). 예전엔 「미감정은 그 카드 자체의
 *    값이라 기준이 된다」며 맨 위에 뒀는데, **그 전제가 틀렸다.** 매물 사진을 직접 읽어
 *    보니 그 칸의 98%가 **감정된 카드**였다 — 저쪽이 제목에서 등급을 못 읽었을 뿐이다.
 *    기준이 되기는커녕 값을 못 쓰는 칸이라(화면에서도 값을 감춘다) 맨 위에 두면
 *    제일 먼저 보이는 줄이 빈 줄이 된다.
 * 감정 기관끼리 묶고, 기관 안에서는 높은 등급부터 센다.
 *
 * 예전엔 **낙찰이 많은 순**이었다. 그러면 블레인의 리자몽에서 PSA 5(14건)가
 * PSA 10(10건)보다 위에 오고 PSA 사이사이에 CGC·BGS가 섞였다. 사람이 카드를
 * 열어 보는 이유는 대개 "PSA 10이 얼마인가"인데 일곱 줄을 훑어야 했다.
 *
 * ⚠️ 이 순서에 기대어 "맨 앞이 대표"라고 쓰면 안 된다. 대표로 보여 줄 등급은
 *    대표등급()이 낙찰 건수로 따로 고른다(api/ebayPrices.ts).
 */
// ⚠️⚠️ **10 위의 등급은 「10.2점」처럼 쳐서 맨 위에 세운다**(2026-08-27).
//    예전엔 `bgsbl10`·`cgcp10`이 아래 정규식(`^[a-z]+숫자$`)에 안 맞아 **9,000으로 밀려
//    맨 끝**에 깔렸다 — 제일 비싼 등급이 BGS 9.5보다도 아래 줄에 있었다.
//    같은 회사 안에서 퍼펙트/블랙라벨 → 프리스틴 → 맨 10점 차례가 되게 값을 매긴다.
const 웃등급: Record<string, { 기관: string; 점: number }> = {
  bgsbl10: { 기관: 'bgs', 점: 10.2 }, // BGS 블랙라벨 — 부분점수 넷이 전부 10
  cgcp10: { 기관: 'cgc', 점: 10.2 }, // CGC 프리스틴 — CGC의 꼭대기(그 아래가 젬민트 10)
};

export function 등급순서값(grade: string): number {
  const g = String(grade).toLowerCase();
  if (g === 'ungraded' || g === 'raw') return 8_000; // 값을 못 쓰는 칸 — 맨 아래(모르는 표기보다는 위)
  const 웃 = 웃등급[g];
  if (웃) {
    const 기관 = 기관우선.indexOf(웃.기관);
    return (기관 < 0 ? 기관우선.length : 기관) * 100 + (100 - 웃.점 * 10);
  }
  const m = g.match(/^([a-z]+)(\d+(?:[._]\d+)?)$/);
  if (!m) return 9_000; // 모르는 표기는 맨 아래. 버리지는 않는다
  const 기관 = 기관우선.indexOf(m[1]);
  const 등급 = Number(m[2].replace('_', '.')) || 0;
  // 기관마다 100칸을 주고, 그 안에서 높은 등급이 앞으로 오게(10 → 0)
  return (기관 < 0 ? 기관우선.length : 기관) * 100 + (100 - 등급 * 10);
}
