// "지금이 며칠인가"를 한국시간으로 정한다. **서버와 화면이 이 한 벌만 쓴다.**
//
// 왜 따로 뺐나: 같은 계산(UTC+9로 옮겨 날짜만 자르기)이 서버 4곳·화면 2곳에 흩어져
// 있었다(2026-08-07 점검에서 확인). 지금은 여섯 벌이 다 같은 답을 내지만, 한 곳만
// 고치면 **화면의 "오늘"과 서버의 "오늘"이 갈린다** — 그러면 출석은 됐다는데 보상은
// 어제 것이거나, 진열대가 화면과 서버에서 다른 팩을 가리키게 된다.
// 같은 규칙을 두 벌로 두었다가 실제로 사고가 난 적이 있다([[koCardName]] 참고).
//
// 왜 한국시간인가: 이용자가 전부 한국이고, 서버(Fly)는 UTC로 돈다. 자정에 바뀌어야
// 할 것들(출석·오늘의 상점·통계 날짜 칸·백업)을 UTC로 끊으면 **한국시간 오전 9시**에
// 바뀐다.
// ⚠️ **PPT 크레딧만은 예외다.** 그건 UTC 자정에 초기화되므로 utcDay()를 쓴다.
//    여기 있는 함수를 거기에 쓰지 말 것.
//
// ⚠️ 이 파일은 **아무것도 가져오지 않는다.** 서버가 가져다 쓰기 때문이다.
// ⚠️ 서버가 쓰므로 **Dockerfile COPY 목록에도 있어야 한다.**
//    `npm run build`의 배포 파일 검사가 빠뜨리면 알려 준다.

const KST = 9 * 60 * 60 * 1000;

/** '2026-08-07' — 한국시간 기준 날짜. */
export const kstDateStr = (now = Date.now()): string => new Date(now + KST).toISOString().slice(0, 10);

/** '2026-08-07T14' — 한국시간 기준 날짜+시각. 검색 순위처럼 시간 단위로 담는 곳에 쓴다. */
export const kstHourStr = (now = Date.now()): string => new Date(now + KST).toISOString().slice(0, 13);

/**
 * 한국시간 기준 "며칠째"인지의 일련번호. 날짜 문자열이 아니라 숫자가 필요한 곳
 * (며칠에 한 바퀴 도는 순번제)에서 쓴다.
 */
export const kstDayNo = (now = Date.now()): number => Math.floor((now + KST) / 86_400_000);
