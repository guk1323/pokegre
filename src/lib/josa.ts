// 이름 뒤에 붙는 조사를 받침에 맞춰 고른다.
//
// ⚠️ 「파오리을(를)」·「뚜벅쵸은(는)」처럼 둘을 다 적으면 읽다가 걸린다. 한글은
//    **받침이 있으면 은/을, 없으면 는/를**이라 글자 하나만 보면 정해진다.
// ⚠️ 한글이 아닌 이름(영문 카드명·숫자)은 판단할 수 없다 — 받침 없는 쪽(는/를)으로 둔다.
//    영어 이름은 대개 그렇게 읽는다.
//
// ⚠️⚠️ **한 벌만 둔다.** 2026-08-13에 팝수 화면에 같은 것을 또 만들다가, 작가 화면
//    (`ArtistsView`)에 이미 있는 것을 발견해 여기로 모았다. 규칙이 두 군데면 한쪽만
//    고쳐 놓고 고쳤다고 여기게 된다.

/** 받침이 있으면 '은', 없으면 '는'. */
export const 은는 = (이름: string): string => (받침있나(이름) ? '은' : '는');

/** 받침이 있으면 '을', 없으면 '를'. */
export const 을를 = (이름: string): string => (받침있나(이름) ? '을' : '를');

function 받침있나(이름: string): boolean {
  const 끝 = 이름.trim().slice(-1);
  const 코드 = 끝.charCodeAt(0);
  // 한글 음절(가~힣)이 아니면 판단하지 않는다.
  if (!(코드 >= 0xac00 && 코드 <= 0xd7a3)) return false;
  // 음절 코드에서 28로 나눈 나머지가 0이면 받침이 없다.
  return (코드 - 0xac00) % 28 !== 0;
}
