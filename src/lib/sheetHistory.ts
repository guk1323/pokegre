// 카드 상세 시트(DetailSheet)가 **스스로** 닫히면서 history.back()을 부를 때 세우는 표식.
//
// 왜 필요한가: 시트는 열릴 때 방문기록에 칸을 하나 쌓고(pushState), 닫힐 때 그 칸을
// 되돌린다(back). 그런데 App의 뒤로가기 처리기는 되돌아간 칸에 적힌 화면 상태(nav)를
// 그대로 복원한다. 그 칸에 적힌 것은 **시트를 열기 전** 상태라, 시트가 열려 있는 동안
// 화면이 바뀌었으면 그 변경이 통째로 되돌려진다.
//
// 실제로 이것 때문에 마켓 탭을 눌러도 원래 마켓으로 되돌아왔다(2026-08-06):
// 탭을 누름 → 검색어·마켓이 바뀜 → 고른 카드가 사라져 시트가 자동으로 닫힘 →
// back() → 예전 nav 복원 → 스니커덩크·"M6 113"로 원위치.
//
// 사람이 뒤로가기 버튼으로 시트를 닫을 때는 이 표식이 서지 않는다(그때는 시트가
// back()을 부르지 않는다). 그 경우는 nav가 화면과 맞으므로 복원해도 된다.
