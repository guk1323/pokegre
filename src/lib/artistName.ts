// 작가 이름을 「한글(원어)」 꼴로 적는다. — 2026-08-14
//
// ⚠️⚠️ **왜 원어를 같이 적나 — 검색에서 이름 표기가 갈리기 때문이다.**
//    서치 콘솔을 보니 같은 작가인데 표기에 따라 순위가 갈렸다(3개월):
//
//      「신지 칸다」(띄어씀 · 페이지에 있던 꼴)  노출 2 · **3.5위**
//      「신지칸다」(붙여씀 · 페이지에 없던 꼴)   노출 5 · **8.8위**
//
//    원어(`Shinji Kanda`)와 순서를 바꾼 꼴(「아리타 미츠히로」)은 페이지 어디에도 없었다.
//    자료에는 `en` 칸이 이미 다 채워져 있는데 화면에 안 내보내고 있었을 뿐이다.
//
// ⚠️ **검색어를 심는 게 아니라 사실을 적는 것이다.** 작가 페이지에 그 사람의 원래 이름을
//    적는 건 그 자체로 쓸모 있는 정보다. 억지로 표기 변형을 늘어놓지 말 것 —
//    「신지칸다」처럼 붙여 쓴 꼴을 따로 박아 넣으면 그건 검색어 심기다.
//
// ⚠️ 규모는 작다. 작가 이름 검색은 3개월 통틀어 노출 25 · 클릭 1이었다. 다만 자료가
//    이미 있어 붙이기만 하면 되고, 작가 페이지는 한 번 들어오면 잘 눌린다(CTR 29~67%).

/**
 * 「신지 칸다(Shinji Kanda)」처럼 한글 뒤에 원어를 괄호로 단다.
 *
 * ⚠️ 둘이 같거나 한쪽이 비면 **하나만** 낸다 — 「5ban Graphics(5ban Graphics)」처럼
 *    같은 말을 두 번 적지 않는다(한글명이 없는 작가가 실제로 있다).
 */
export function 작가이름(ko?: string | null, en?: string | null): string {
  const k = (ko ?? '').trim();
  const e = (en ?? '').trim();
  if (!k) return e;
  if (!e || k === e) return k;
  return `${k}(${e})`;
}
