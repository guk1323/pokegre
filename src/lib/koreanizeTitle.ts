// ja-VS1(포켓몬 카드 ★VS)의 성도 관장 소유격 표기. 원본 DB가 영어명을 가타카나로
// 음차해 갖고 있어 사전에 안 잡힌다(フォークナー=Falkner=비상). 검색 역번역을 깨지
// 않도록 STRUCTURAL_TERMS가 아니라 koreanizeTitle 안에서 한 방향으로만 쓴다.
const VS_TRAINER_PREFIXES: [string, string][] = [
  ['フォークナーの', '비상의 '],
  ['ホイットニーの', '꼭두의 '],
  ['ジャスミンの', '규리의 '],
  ['プライスの', '류옹의 '],
  ['モーティの', '유빈의 '],
  ['チャックの', '사도의 '],
  ['クレアの', '이향의 '],
  ['カレンズ', '카렌의 '],
];

function replaceKnownPackNames(title: string): string {
  let result = title;
  for (const [ja, ko] of MANUAL_PACK_OVERRIDES) {
    if (result.includes(ja)) {
      result = result.split(ja).join(ko);
    }
  }
  for (const entry of sortedPackEntries) {
    if (result.includes(entry.ja)) {
      result = result.split(entry.ja).join(entry.ko);
    }
  }
  return result;
}

// 카드명에서 포켓몬 종 이름(일본어)만 한글로 바꾸고, ex/GX/SAR 같은 접미사는
// 그대로 둔다. 카드명은 공백 없이 이름과 접미사가 붙어 있는 경우가 많아
// (예: "メガゲッコウガex") 토큰 분리 대신 부분 문자열 치환을 사용한다.
//
// 팩/시리즈 이름은 pokecardmon.com이 정리해둔 한글 표기를 우선 쓰고, 거기
// 없는 경우에만 가나 발음을 한글로 옮기는 음역으로 대체한다(장음부호·촉음
// 생략하는 간이 규칙이라 실제 정식 표기와는 다를 수 있음).
export function koreanizeTitle(title: string): string {
  let result = replaceKnownPackNames(title);

  for (const entry of sortedPokemonEntries) {
    if (result.includes(entry.ja)) {
      result = result.split(entry.ja).join(entry.ko);
    }
  }

  // 정식 이름으로 못 잡은 것만 오염 표기 별칭으로 한 번 더 잡는다.
  for (const entry of sortedAliasEntries) {
    if (result.includes(entry.ja)) {
      result = result.split(entry.ja).join(entry.ko);
    }
  }

  for (const [ja, ko] of STRUCTURAL_TERMS) {
    result = result.split(ja).join(ko);
  }

  // "第5弾"(다섯 번째 발매분)처럼 숫자만 바뀌는 표현은 고정 사전 대신 정규식으로 처리한다.
  result = result.replace(/第(\d+)弾/g, '제$1탄');

  // 중국어판 카드 제목에 병기된 "(皮卡丘)" 같은 중국어 중복 표기 제거. STRUCTURAL_TERMS는
  // translateQuery.ts가 검색어 번역용으로 반대 방향(한글→일본어)으로도 재사용하는데,
  // 거기서 빈 문자열을 키로 쓰면 모든 문자 사이에 값이 끼어드는 버그가 생기므로 STRUCTURAL_TERMS에
  // 넣지 않고 여기서 한쪽 방향으로만 지운다.
  // 괄호가 반각·전각이거나 없는 경우까지 모두 잡아 중국어 피카츄 병기를 지운다.
  result = result.replace(/[（(]?皮卡丘[）)]?/g, '');

  // 仕様(사양/버전 표기)는 카드명에서 "사양"으로 옮기면 어색해 그냥 지운다. STRUCTURAL에
  // 빈 값으로 넣으면 translateQuery 역변환이 깨지므로 여기서 한쪽 방향으로만 제거한다.
  result = result.split('仕様').join('');

  // ja-VS1 등 옛 세트는 원본 DB에 "Surge's Raichu中t"처럼 뜻 없는 꼬리가 붙어 있다.
  // 빈 값은 STRUCTURAL에 못 넣으므로(검색 역번역이 깨진다) 여기서 한쪽 방향으로만 지운다.
  result = result.split('中t').join('');

  // VS 시리즈(ja-VS1)는 원본 DB가 트레이너 이름을 영어명의 가타카나 음차로 갖고 있다
  // (フォークナー=Falkner). 소유격 の까지 묶어 성도 관장들의 정식 한글명으로 옮긴다.
  // STRUCTURAL에 넣으면 "규리의"→ジャスミンの처럼 역번역이 깨져(공식 카드는 ミカン),
  // 검색이 망가지므로 여기서 한쪽 방향으로만 바꾼다.
  for (const [ja, ko] of VS_TRAINER_PREFIXES) {
    result = result.split(ja).join(ko);
  }

  // 날짜 표기(잡지 발매월 등)의 한자. 単독 年/月/日을 STRUCTURAL에 넣으면 검색어
  // 역번역(한글→일본어)에서 "일"·"월" 같은 흔한 글자를 잘못 바꿀 수 있어, 숫자 뒤
  // 날짜일 때만 한쪽 방향으로 바꾼다.
  result = result.replace(/(\d+)年/g, '$1년').replace(/(\d+)月/g, '$1월').replace(/(\d+)日/g, '$1일');
  result = result.replace(/第(\d+)期/g, '제$1기');
  // 대회 순위 표기("1位"). 단독 位는 흔한 글자라 숫자 뒤일 때만 바꾼다.
  result = result.replace(/(\d+)位/g, '$1위');
  result = result.replace(/第(\d+)回/g, '제$1회');
  // "100名限定" 같은 인원 표기. 단독 名은 흔해서 숫자 뒤일 때만 바꾼다.
  result = result.replace(/(\d+)名/g, '$1명');
  // 잡지 "第2号"·"7月号" 같은 호수 표기. 号도 숫자 뒤일 때만 바꾼다.
  result = result.replace(/第(\d+)号/g, '제$1호').replace(/(\d+)号/g, '$1호');

  // 소유격 조사 の는 팩·카드 이름 곳곳에 남는데(에리카の招待 등) 앞의 개별 컴파운드에서
  // 못 잡으면 음역으로 "노"가 돼 어색하다. 어떤 맥락이든 "의"라, 남은 の는 여기서 한쪽
  // 방향으로만 바꾼다(STRUCTURAL에 넣으면 translateQuery 역번역에서 흔한 "의"를 の로
  // 잘못 되돌린다). 단, "してんのう"(사천왕)처럼 히라가나 단어 속 の까지 바꾸면 깨지므로,
  // 뒤에 한자·카타카나·한글(이미 바뀐 이름)이 오는 소유격 の만 바꾼다.
  result = result.replace(/の(?=[가-힣゠-ヿ一-鿿])/g, '의 ');

  // 옛 팩·에너지 이름에 홀로 남는 원소 한자. 포켓몬 이름은 이미 앞에서 바뀌었다.
  result = result.split('水').join('물').split('炎').join('불꽃').split('闇').join('어둠').split('草').join('풀');
  result = result.split('丘').join('언덕').split('版').join('판').split('賞').join('상');
  result = result.split('悪').join('악').split('夜').join('밤').split('震').join('진');
  // "2個" 같은 개수 표기. 単독 個는 흔해서 숫자 뒤일 때만 바꾼다.
  result = result.replace(/(\d+)個/g, '$1개');
  // "15周年" 같은 주년 표기. 周도 숫자 뒤일 때만 바꾼다.
  result = result.replace(/(\d+)周/g, '$1주');

  // 에너지 타입 표기로 홀로 남는 雷(번개). 迅雷 같은 팩 이름은 앞 단계에서 이미 처리된다.
  result = result.split('雷').join('번개');

  // 幻(환)·중점(・)은 흔한 글자라 역번역을 깨지 않도록 한쪽 방향으로만 정리한다.
  result = result.split('幻').join('환').split('・').join('·');

  // 戦(전)은 対戦·争奪戦처럼 대부분 앞 규칙에서 잡히지만, "シールド戦"은 packNames의
  // 단독 "シールド"가 먼저 걸려 戦만 남는다. 어떤 맥락이든 "전"이라 한쪽 방향으로 마무리.
  result = result.split('戦').join('전');

  return kanaToHangul(result);
}
