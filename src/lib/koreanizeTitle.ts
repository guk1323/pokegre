function replaceKnownPackNames(title: string): string {
  let result = title;
  for (const [ja, ko] of MANUAL_PACK_OVERRIDES) {
    if (result.includes(ja)) {
      result = result.split(ja).join(ko);
    }
  }
  for (const entry of sortedPackEntries) {
    if (result.includes(entry.ja)) {
      result = result.split(entry.ja).join(entry.ko);
    }
  }
  return result;
}

// 카드명에서 포켓몬 종 이름(일본어)만 한글로 바꾸고, ex/GX/SAR 같은 접미사는
// 그대로 둔다. 카드명은 공백 없이 이름과 접미사가 붙어 있는 경우가 많아
// (예: "メガゲッコウガex") 토큰 분리 대신 부분 문자열 치환을 사용한다.
//
// 팩/시리즈 이름은 pokecardmon.com이 정리해둔 한글 표기를 우선 쓰고, 거기
// 없는 경우에만 가나 발음을 한글로 옮기는 음역으로 대체한다(장음부호·촉음
// 생략하는 간이 규칙이라 실제 정식 표기와는 다를 수 있음).
export function koreanizeTitle(title: string): string {
  const whole = EXACT_TITLES.get(title.trim());
  if (whole) return whole;

  let result = replaceKnownPackNames(title);

  // ⚠️ **델타종 표기를 한 꼴로 모은다.** 일본판 원본이 "スピアーδ-デルタ種"처럼
  //    **δ와 デルタ種을 둘 다** 적어 둔다. 그대로 두면 δ는 한글로 안 바뀌고 デルタ種만
  //    바뀌어 "독침붕δ-델타종"이 되고, 이름 뒤에 한 칸이 있는 것("ギャラドス δ-デルタ種")은
  //    영문 쪽 규칙(' δ' → ' (델타종)')까지 걸려 **"갸라도스 (델타종)-델타종"**이 된다.
  //    2026-08-08 실측으로 델타종 카드 339장 중 **147장이 이렇게 깨져** 있었다.
  //    같은 카드가 북미판에서는 "독침붕 (델타종)"으로 멀쩡히 나와 판마다 이름이 갈렸다.
  //    → 겹쳐 적힌 것을 전각 괄호 한 꼴로 모은다. 뒤의 괄호 처리가 " (델타종)"으로 만든다.
  result = result.replace(/\s*δ\s*-\s*デルタ種/g, '（デルタ種）');

  // 포켓몬 이름을 품은 낱말은 이름 사전보다 먼저 잡는다(위 COMPOUND_TERMS 설명 참고).
  for (const [ja, ko] of COMPOUND_TERMS) result = result.split(ja).join(ko);

  // 정식 이름과 별칭을 한 번에, 긴 것부터 본다. 별칭을 뒤로 미루면 "ヒートロトム"의
  // ロトム이 먼저 걸려 "히토로토무"가 된다. 긴 것부터 보면 별칭이 이겨 통째로 잡히고,
  // 짧은 별칭(ラプラ)은 정식 이름(ラプラス)보다 뒤라 여전히 안 끼어든다.
  for (const entry of sortedNameEntries) {
    if (entry.exactOnly) {
      if (result === entry.ja) result = entry.ko;
      continue;
    }
    if (result.includes(entry.ja)) {
      result = result.split(entry.ja).join(entry.ko);
    }
  }

  for (const [ja, ko] of STRUCTURAL_TERMS) {
    result = result.split(ja).join(ko);
  }

  // "第5弾"(다섯 번째 발매분)처럼 숫자만 바뀌는 표현은 고정 사전 대신 정규식으로 처리한다.
  result = result.replace(/第(\d+)弾/g, '제$1탄');

  // 중국어판 카드 제목에 병기된 "(皮卡丘)" 같은 중국어 중복 표기 제거. STRUCTURAL_TERMS는
  // translateQuery.ts가 검색어 번역용으로 반대 방향(한글→일본어)으로도 재사용하는데,
  // 거기서 빈 문자열을 키로 쓰면 모든 문자 사이에 값이 끼어드는 버그가 생기므로 STRUCTURAL_TERMS에
  // 넣지 않고 여기서 한쪽 방향으로만 지운다.
  // 괄호가 반각·전각이거나 없는 경우까지 모두 잡아 중국어 피카츄 병기를 지운다.
  result = result.replace(/[（(]?皮卡丘[）)]?/g, '');

  // 仕様(사양/버전 표기)는 카드명에서 "사양"으로 옮기면 어색해 그냥 지운다. STRUCTURAL에
  // 빈 값으로 넣으면 translateQuery 역변환이 깨지므로 여기서 한쪽 방향으로만 제거한다.
  result = result.split('仕様').join('');

  // ja-VS1 등 옛 세트는 원본 DB에 "Surge's Raichu中t"처럼 뜻 없는 꼬리가 붙어 있다.
  // 빈 값은 STRUCTURAL에 못 넣으므로(검색 역번역이 깨진다) 여기서 한쪽 방향으로만 지운다.
  result = result.split('中t').join('');

  // VS 시리즈(ja-VS1)는 원본 DB가 트레이너 이름을 영어명의 가타카나 음차로 갖고 있다
  // (フォークナー=Falkner). 소유격 の까지 묶어 성도 관장들의 정식 한글명으로 옮긴다.
  // STRUCTURAL에 넣으면 "규리의"→ジャスミンの처럼 역번역이 깨져(공식 카드는 ミカン),
  // 검색이 망가지므로 여기서 한쪽 방향으로만 바꾼다.
  for (const [ja, ko] of VS_TRAINER_PREFIXES) {
    result = result.split(ja).join(ko);
  }
  for (const [ja, ko] of ONE_WAY_NAMES) {
    result = result.split(ja).join(ko);
  }

  // 날짜 표기(잡지 발매월 등)의 한자. 単독 年/月/日을 STRUCTURAL에 넣으면 검색어
  // 역번역(한글→일본어)에서 "일"·"월" 같은 흔한 글자를 잘못 바꿀 수 있어, 숫자 뒤
  // 날짜일 때만 한쪽 방향으로 바꾼다.
  result = result.replace(/(\d+)年/g, '$1년').replace(/(\d+)月/g, '$1월').replace(/(\d+)日/g, '$1일');
  result = result.replace(/第(\d+)期/g, '제$1기');
  // 대회 순위 표기("1位"). 단독 位는 흔한 글자라 숫자 뒤일 때만 바꾼다.
  result = result.replace(/(\d+)位/g, '$1위');
  result = result.replace(/第(\d+)回/g, '제$1회');
  // "100名限定" 같은 인원 표기. 단독 名은 흔해서 숫자 뒤일 때만 바꾼다.
  result = result.replace(/(\d+)名/g, '$1명');
  // 잡지 "第2号"·"7月号" 같은 호수 표기. 号도 숫자 뒤일 때만 바꾼다.
  result = result.replace(/第(\d+)号/g, '제$1호').replace(/(\d+)号/g, '$1호');

  // 소유격 조사 の는 팩·카드 이름 곳곳에 남는데(에리카の招待 등) 앞의 개별 컴파운드에서
  // 못 잡으면 음역으로 "노"가 돼 어색하다. 어떤 맥락이든 "의"라, 남은 の는 여기서 한쪽
  // 방향으로만 바꾼다(STRUCTURAL에 넣으면 translateQuery 역번역에서 흔한 "의"를 の로
  // 잘못 되돌린다). 단, "してんのう"(사천왕)처럼 히라가나 단어 속 の까지 바꾸면 깨지므로,
  // 뒤에 한자·카타카나·한글(이미 바뀐 이름)이 오는 소유격 の만 바꾼다.
  // 알파벳도 포함한다. 옛 VS·PCG 세트는 원본 데이터에 인물 이름이 영어로 섞여 와
  // "RocketのMewtwo"처럼 の 뒤에 알파벳이 온다. 이걸 빼두면 "Rocket노뮤츠"가 됐다.
  result = result.replace(/の(?=[가-힣゠-ヿ一-鿿A-Za-z])/g, '의 ');

  // "A와 B"의 と. 포켓몬 이름이 먼저 한글로 바뀌므로 여기선 "뮤と파동"처럼 남아 있다.
  // 앞뒤가 모두 글자일 때만 바꾼다 — 낱말 속 と(ゲットだ 등)는 건드리지 않는다.
  result = result.replace(/(?<=[가-힣])と(?=[가-힣゠-ヿ一-鿿])/g, '와 ');

  // 같은 옛 세트에는 영어식 소유격도 섞여 온다("Bugsy's Pinsir"). 앞이 이미 한글로
  // 바뀐 이름일 때만 "의"로 옮긴다 — 영어로 남은 이름에 붙이면 "Rocket의"처럼
  // 반쪽짜리가 되어 오히려 읽기 나쁘다.
  result = result.replace(/(?<=[가-힣])['’]s\s+/g, '의 ');

  // 앞말 사전에 꼬리 공백이 있으면("パルデア" → "팔데아 ") 조사 앞에 공백이 낀다
  // ("팔데아 의 동료들"). 한글 뒤에 붙는 조사 앞의 공백만 지운다.
  result = result.replace(/(?<=[가-힣])\s+(?=의\s)/g, '').replace(/ {2,}/g, ' ');

  // 원본 목록에 마침표가 딸려 온 이름이 있다("ロケットの管理者。"). 카드 이름에 마침표가
  // 붙어 있으면 잘못 들어간 것처럼 보이니 끝에 붙은 것만 뗀다.
  // 에너지 카드는 "[이름] 에너지"가 공식 표기다(2026-08-02 사용자 확인).
  // 조각들이 붙어 조립된 결과에 공백을 넣어 준다. 이미 띄어져 있으면 그대로 둔다.
  result = result.replace(/([^\s])에너지/g, '$1 에너지');

  result = result.replace(/。\s*$/, '');

  // 일본어 전각 괄호（）가 한글 사이에 그대로 남는다("독침붕（델타종）"). 한글 표기로 바꾸고
  // 앞에 한 칸 띄운다 — 붙어 있으면 이름의 일부처럼 읽힌다.
  // 닫는 괄호 뒤에 ex·V 같은 꼬리가 붙는 것도 띄운다("(델타종)ex" → "(델타종) ex").
  result = result
    .replace(/（/g, ' (')
    .replace(/）/g, ')')
    .replace(/\)(?=[A-Za-z가-힣])/g, ') ')
    .replace(/ {2,}/g, ' ')
    .trim();

  // 옛 팩·에너지 이름에 홀로 남는 원소 한자. 포켓몬 이름은 이미 앞에서 바뀌었다.
  result = result.split('水').join('물').split('炎').join('불꽃').split('闇').join('어둠').split('草').join('풀');
  result = result.split('丘').join('언덕').split('版').join('판').split('賞').join('상');
  result = result.split('悪').join('악').split('夜').join('밤').split('震').join('진');
  // "2個" 같은 개수 표기. 単독 個는 흔해서 숫자 뒤일 때만 바꾼다.
  result = result.replace(/(\d+)個/g, '$1개');
  // "15周年" 같은 주년 표기. 周도 숫자 뒤일 때만 바꾼다.
  result = result.replace(/(\d+)周/g, '$1주');

  // 에너지 타입 표기로 홀로 남는 雷(번개). 迅雷 같은 팩 이름은 앞 단계에서 이미 처리된다.
  result = result.split('雷').join('번개');

  // 幻(환)·중점(・)은 흔한 글자라 역번역을 깨지 않도록 한쪽 방향으로만 정리한다.
  result = result.split('幻').join('환').split('・').join('·');

  // 戦(전)은 対戦·争奪戦처럼 대부분 앞 규칙에서 잡히지만, "シールド戦"은 packNames의
  // 단독 "シールド"가 먼저 걸려 戦만 남는다. 어떤 맥락이든 "전"이라 한쪽 방향으로 마무리.
  result = result.split('戦').join('전');

  // 옛 e카드 세트(ja-E2)는 카드 이름 뒤에 번호가 붙어 있다("MUK -004/092" 44장).
  // 화면에는 이름만 나와야 한다 — 번호는 대괄호로 따로 붙는다.
  // ⚠️ 앞에 붙임표가 있을 때만 뗀다. 「호론의 연구탑하프덱1/2」처럼 이름의 일부인
  //    분수는 붙임표가 없어 안 걸린다.
  result = result.replace(/\s*-\s*\d+\/\d+\s*$/, '').trim();

  return 다크를나쁜으로(spaceCardSuffix(kanaToHangul(result)));
}

/**
 * "다크<포켓몬>" → "나쁜 <포켓몬>".
 *
 * ⚠️ **원본 자료가 옛 세트 13장의 이름을 영어 그대로 가타카나로 적어 놨다**
 *    ("ダークジェンガー" — 진짜 일본어는 「わるいゲンガー」다. ja-neo4 10장·ja-web1 3장).
 *    그대로 두면 같은 카드가 판에 따라 다른 이름으로 보인다(2026-08-08 실측):
 *        일본판 ダークジェンガー → "다크팬텀"   ↔   북미판 Dark Gengar → "나쁜 팬텀"
 *    영문판 쪽은 이미 'Dark ' → '나쁜 ' 규칙이 있으므로 그쪽에 맞춘다.
 *
 * ⚠️ **뒤가 포켓몬 이름일 때만 바꾼다.** 안 그러면 멀쩡한 이름이 깨진다 —
 *    다크라이(포켓몬)·다크펫(팬텀의 진화형)·다크볼·다크패치·다크벨은 그대로 둬야 한다.
 */
const 포켓몬한글이름 = new Set((pokemonNames as { ko: string }[]).map((p) => p.ko).filter(Boolean));

const 다크를나쁜으로 = (s: string): string => {
  if (!s.startsWith('다크')) return s;
  const 뒤 = s.slice(2);
  return 포켓몬한글이름.has(뒤.replace(/\s+(ex|EX|GX|V|VMAX|VSTAR)$/, '').trim()) ? '나쁜 ' + 뒤 : s;
};

// 공식 한국 카드명은 꼬리표를 띄어 쓴다("리자몽 ex"·"리자몽 GX"·"리자몽 VSTAR" —
// pokemoncard.co.kr 확인). 일본어 원문은 띄어쓰기가 없어 "리자몽ex"로 붙어 나왔는데,
// 영문판 경로(koreanizeEnglishCardName)는 이미 띄어 써서 같은 카드가 판에 따라 다르게
// 보였다. 여기서 일본판도 공식 표기에 맞춘다.
//   · 앞이 한글일 때만 띄운다 — "폴리곤Z"처럼 꼬리표가 아니라 이름의 일부인 경우가 있다.
//   · 뒤에 영문자가 이어지면 건드리지 않는다("위루노exeggutor"처럼 한 단어인 경우).
//   · 메가 X·Y형은 영문 공식명("Mega Charizard X ex")과 같게 "메가리자몽 X ex"로.
function spaceCardSuffix(name: string): string {
  return name
    .replace(/([가-힣])([XY])(ex|EX)(?![A-Za-z])/g, '$1 $2 $3')
    .replace(/([가-힣])(VMAX|VSTAR|GX|EX|Ex|ex|V)(?![A-Za-z])/g, '$1 $2');
}
