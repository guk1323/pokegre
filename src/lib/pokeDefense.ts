/**
 * 무리에서 **역할**을 정한다. 종족값으로 정하되, 그 스테이지에서 **공이 제일 높은 하나는
 * 원거리**로 둔다.
 * ⚠️ 원거리 적이 하나는 있어야 **벽만 세우는 수가 막힌다** — 원거리는 내 벽 뒤를 때린다.
 */
function 역할정하기(무리: number[]): Map<number, 역할> {
  const 것 = 무리.map((id) => 도감맵.get(id)!);
  const 최고공 = 것.reduce((a, b) => (b.공 > a.공 ? b : a));
  const m = new Map<number, 역할>();
  for (const p of 것) {
    if (p.id === 최고공.id) m.set(p.id, '원거리');
    else if (p.총합 <= 265) m.set(p.id, '벽');
    else if (p.hp >= 75) m.set(p.id, '탱커');
    else m.set(p.id, '근접');
  }
  return m;
}

export function 스테이지빚기(틀: 틀, r: number, c: 곡선꼴 = 곡선, 난: 난이도 = '보통'): 스테이지 {
  const 난배 = 난이도표[난];
  const 역 = 역할정하기(틀.무리);
  // ⚠️ 난이도가 적 수를 잡는다 — 제일 안전한 손잡이다(위 `난이도표` 설명 참고).
  const 수 = Math.max(4, Math.round(c.적수(r) * 난배.수));
  const 적: 나옴[] = [];
  // ⚠️⚠️⚠️ **적은 「파상공세」로 온다 — 찔끔찔끔이 아니다.** 이게 이 게임에 결정거리를 만든다.
  //    처음에는 일정한 간격으로 내보냈는데, 그러면 **아낄 이유가 없어 늘 다 내는 게 정답**이었다.
  //    실측(2026-08-17): 「다 내기」가 12판 전부 이기고 ★★★까지 자동으로 나왔고, 돈을 조여도
  //    (벌이를 13→4로) 여전히 「다 내기」가 제일 나았다. 잣대를 시간으로 바꿔 봐도 마찬가지였다.
  //    → **몰려올 때와 쉴 때를 나누면** 「지금 아꼈다가 몰아 낼까」가 매 순간 판단이 된다.
  //    ⚠️ 묶음 사이 쉬는 참을 없애지 말 것. 그 참이 곧 「모을 시간」이다.
  const 묶음수 = Math.min(5, 3 + Math.floor((r - 1) / 5));
  const 묶음크기 = Math.ceil(수 / 묶음수);
  const 묶음안 = 0.9;                       // 몰려올 때는 바짝 붙어 온다
  // ⚠️ **난이도가 여기를 잡는다.** 쉬는 타임이 곧 「모을 시간」이라, 줄이면 방어가 얇아져
  //    전선이 밀린다 — 돈·성 체력으로는 안 나던 「고전」이 여기서 나온다.
  const 묶음사이 = Math.max(6, (17 - (r - 1) * 0.5) * 난배.쉼)
  let 때 = 3;
  for (let i = 0; i < 수; i++) {
    // ⚠️ 앞에서는 약한 것, 뒤로 갈수록 무리의 뒤쪽(센 것)이 나온다.
    const 몫 = i / Math.max(1, 수 - 1);
    const k = Math.min(틀.무리.length - 1, Math.floor(몫 * 틀.무리.length));
    const id = 틀.무리[k];
    적.push({ 초: Number(때.toFixed(1)), id, 역할: 역.get(id)! });
    때 += (i + 1) % 묶음크기 === 0 ? 묶음사이 : 묶음안;
  }
  if (틀.보스) 적.push({ 초: Number((때 + 4).toFixed(1)), id: 틀.보스, 역할: '원거리', 세기: c.보스세기(r) });

  const 속성 = [...new Set(틀.무리.flatMap((id) => 도감맵.get(id)!.타입))].map((t) => 타입한글[t]);
  return {
    이름: 틀.이름,
    설명: `${틀.한마디 ? 틀.한마디 + ' ' : ''}${속성.join('·')} 속성이 나옵니다.${틀.보스 ? ' 마지막에 보스가 옵니다.' : ''}`,
    적성hp: c.적성hp(r),
    내성hp: Math.round(c.내성hp(r) * 난배.내성),
    // ⚠️ 난이도 `세기`는 **아주 조금만** 곱한다(0.92 · 1.0 · 1.12). 크게 올리면 절벽이 된다.
    적세기: Number((c.적세기(r) * (틀.손질 ?? 1) * 난배.세기).toFixed(3)),
    마침말: 틀.마침말 ?? '', 배경: 틀.배경 ?? '들판',
    /**
     * ⚠️⚠️⚠️ **지갑은 그 판에서 제일 비싼 카드보다 커야 한다.**
     *    사장님 지적(2026-08-18): "전체 재화가 380인데 520 잠만보는 어떻게 쓰라고 둔거야".
     *    1판 지갑이 380인데 덱에 잠만보(520)가 들어 있어 **한 판 내내 절대 못 사는 카드**가
     *    여덟 중 하나였다. 화면에는 멀쩡히 떠 있으니 「돈을 더 모으면 되나」 하고 기다리게 된다.
     *    ⚠️ 검사기도 못 잡았다 — 「다 내기」가 못 사는 것을 **조용히 건너뛰기** 때문이다.
     *    ⚠️ 그래서 규칙에서 못을 박는다. 판을 새로 더해도 이 잘못이 다시 안 생긴다.
     *    ⚠️ 1.05를 곱하는 것은 **딱 맞으면 지갑이 꽉 차야만 살 수 있어** 사실상 못 쓰기 때문이다.
     */
    벌이: Number((c.벌이(r) * 난배.벌이).toFixed(2)),
    지갑: Math.max(c.지갑(r), Math.ceil(Math.max(...판덱(r - 1).map((u) => u.값)) * 1.05)),
    시작돈: c.시작돈(r),
    적,
  };
}

