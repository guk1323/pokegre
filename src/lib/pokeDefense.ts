/** 지금 판에 적이 남아 있나(살아 있는 적 + 아직 안 나온 적). */
export function 적있나(p: 판): boolean {
  return p.놈들.some((n) => !n.우리편 && n.hp > 0);
}

/** 적 한 마리를 스테이지 표에서 빚는다. */
export function 적유닛(n: 나옴, 세기 = 1): 유닛 {
  return 유닛만들기(n.id, n.역할, 0, 0, (n.세기 ?? 1) * 세기);
}

