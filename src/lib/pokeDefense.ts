/**
 * 해금된 포켓몬의 **값**. 종족값 총합에서 뽑는다.
 *
 * ⚠️⚠️ **이게 「센 걸 얻어도 안 무너지는」 장치다.** 팬텀·리자몽을 얻어도 값이 비싸
 *    함부로 못 낸다. 값을 고정으로 두면 뒤에 얻은 센 것이 앞 스테이지를 통째로 뭉갠다.
 * ⚠️ 지수 2.8은 **손으로 매긴 여덟에 맞춘 값**이다(캐터피 30→30 · 꼬부기 110→114 ·
 *    후딘 380→419 · 잠만보 520→520). 바꾸려면 그 여덟과 다시 맞대 볼 것.
 */
function 값매기기(총합: number): number {
  return Math.max(20, Math.round(30 * Math.pow(총합 / 195, 2.8)));
}

/**
 * 포켓몬 하나의 **역할**을 종족값에서 정한다.
 *
 * ⚠️⚠️⚠️ **네 갈래는 「무엇을 잘하나」로 가른다.** 순서가 곧 규칙이다 —
 *    ①때릴 힘이 없나 ②몸이 아주 좋나 ③멀리서 때리나 ④나머지.
 *
 * ⚠️ **벽은 「총합이 낮은 것」이 아니다.** 처음에 `총합 ≤ 265`로 했다가 **디그다(종족 hp 10)와
 *    잉어킹(hp 20)이 벽**이 됐다 — 막을 몸이 없어 한 대에 죽는다(2026-08-17에 잡음).
 *    벽은 **때릴 힘이 없는데 몸은 있는 것**이다. 그래서 두 조건을 다 본다.
 * ⚠️ **탱커 기준을 조였다.** `hp ≥ 78 또는 방 ≥ 95`로 뒀더니 151마리 중 61마리(40%)가
 *    탱커가 됐다. 「아주 좋은 몸」이 40%면 뜻이 없다 — hp 90 / 방어 100으로 올렸다.
 * ⚠️ **원거리는 원작이 정한다** — 특수공격이 물리공격보다 높으면 멀리서 때리는 포켓몬이다.
 *    앞서 「공 ≥ 방 + 20」이라는 **내가 지어낸 잣대**를 썼는데, 그러면 닥트리오·알통몬처럼
 *    원작에서 몸으로 싸우는 것이 원거리가 됐다.
 */
function 역할매기기(p: 포켓몬): 역할 {
  const 때림 = Math.max(p.공, p.특공);
  // ① 때릴 힘이 없는데 몸은 있다 → 벽. (hp 35는 「한 대는 버틴다」는 선이다)
  if (때림 <= 45 && p.hp >= 35) return '벽';
  // ② 몸이 아주 좋다 → 탱커. 상위 20%쯤만 들어온다.
  if (p.hp >= 90 || p.방 >= 100) return '탱커';
  // ③ 특수형이면 뒤에서 때린다.
  if (p.특공 > p.공) return '원거리';
  // ④ 나머지는 앞에서 때린다.
  return '근접';
}


/** 도감번호 하나를 쓸 수 있는 유닛으로 바꾼다. */
export function 유닛으로(id: number): 유닛 {
  const 손 = 손으로.get(id);
  if (손) return 유닛만들기(손.id, 손.역, 손.값, 손.쿨);
  const p = 도감맵.get(id)!;
  const 값 = 값매기기(p.총합);
  // ⚠️ 쿨도 값을 따라간다. 센 것을 자주 내면 값이 뜻을 잃는다.
  return 유닛만들기(id, 역할매기기(p), 값, Number((2 + 값 * 0.04).toFixed(1)));
}

/** 진화 계보를 통째로 편다(자기 자신 포함). */
export function 계보(id: number): number[] {
  const 것: number[] = [];
  let 지금: number | undefined = id;
  while (지금 != null && !것.includes(지금)) { 것.push(지금); 지금 = 도감맵.get(지금)?.진화 ?? undefined; }
  return 것;
}

/** 아무것도 안 깬 처음 여덟. 검사 스크립트와 첫 덱이 쓴다. */
export const 내유닛: 유닛[] = 기본보유.map(유닛으로);

