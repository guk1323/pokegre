  /**
   * 이 스테이지 적 전체의 세기 배수. **난이도는 여기 하나로 잡는다** —
   * 적을 한 마리씩 손보면 어디가 어려운지 알 수 없게 된다.
   * ⚠️ 실제로 돌려 보고 정한 값이다(`npx tsx scripts/sim-poke-defense.mts`). 눈으로 정하지 말 것.
   */
  적세기: number;
  /** 깨고 나서 뜨는 한 줄. */
  마침말: string;
  /** 전장 배경 갈래. `index.css`의 `.판-…` 클래스와 짝이다. */
