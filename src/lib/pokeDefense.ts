/**
 * 스테이지의 적을 **무리(파상공세) 단위로** 묶는다.
 * ⚠️ 나오는 시각의 **틈이 4초를 넘으면** 다음 무리로 본다(무리 안은 0.9초 간격, 사이는 9초 이상).
 *    `스테이지빚기`의 간격을 바꾸면 이 값도 같이 봐야 한다.
 */
export function 무리들(s: 스테이지): 나옴[][] {
  const 것: 나옴[][] = [];
  let 지금: 나옴[] = [];
  let 앞 = -99;
  for (const n of s.적) {
    if (지금.length && n.초 - 앞 > 4) { 것.push(지금); 지금 = []; }
    지금.push(n);
    앞 = n.초;
  }
  if (지금.length) 것.push(지금);
  return 것;
}

/**
 * **다음 무리까지 몇 초 남았나.** 아직 안 나온 적이 없으면 null.
 *
 * ⚠️⚠️ **이게 없으면 별을 딸 수가 없다.** ★★★은 「쉬는 참에 안 쓰기」로 따는데, 언제가
 *    쉬는 참인지 화면에 안 나오면 **배울 방법이 없다**(2026-08-17에 빠뜨린 걸 잡았다).
 *    규칙이 요구하는 것은 반드시 화면에 보여야 한다.
 */
export function 다음무리까지(p: 판, s: 스테이지): number | null {
  const 다음 = s.적[p.다음적];
  return 다음 ? Math.max(0, 다음.초 - p.t) : null;
}

