//    `해금`·`보유목록`·`진화단계`가 여기 있었다. 시즌1은 판마다 여덟이 고정이다.

/**
 * 그 판에서 쓸 수 있는 여덟. **값이 싼 것부터** 놓는다.
 *
 * ⚠️⚠️ **화면에 놓이는 차례가 곧 이 차례다.** 정렬을 안 했더니 1판만 오름차순이고
 *    **나머지 열한 판이 뒤죽박죽**이었다(3판: 30·110·202·120·105·60·100·140).
 *    1판에서 「왼쪽이 싼 것」을 배운 사람이 2판부터 그 규칙이 깨진다 — 숫자키 1~8도
 *    같은 차례라 손이 기억한 자리가 판마다 다른 것을 낸다.
 * ⚠️⚠️ **셈에도 영향이 있다.** 「보이는 대로 다 내기」는 이 차례대로 사므로, 싼 카드가
 *    앞에 끼면 뒤에 있는 좋은 카드의 돈을 가로챈다. 검사기 주석은 「싼 것부터 다 낸다」라고
 *    적혀 있었는데 실제로는 **덱에 적힌 차례**였다 — 이제 둘이 같아졌다.
 * ⚠️ 값이 같으면 적어 둔 차례를 지킨다(`sort`는 제자리 정렬이라 안정적이다).
 */
export function 판덱(스테이지번호: number): 유닛[] {
  return (틀들[스테이지번호]?.덱 ?? 기본보유).map(유닛으로).sort((a, b) => a.값 - b.값);
}

