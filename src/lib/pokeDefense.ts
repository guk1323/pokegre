export interface 유닛 {
  id: number;
  ko: string;
  타입: string[];
  역할: 역할;
  값: number;      // 소환 비용
  쿨: number;      // 재사용 대기(초)
  hp: number;
  공: number;
  사거리: number;
  속도: number;    // 초당 몇 칸
  간격: number;    // 몇 초마다 때리나
}

function 유닛만들기(id: number, 역: 역할, 값: number, 쿨: number, 세기 = 1): 유닛 {
  const p = 도감맵.get(id)!;
  const b = 역할배수[역];
  /**
   * ⚠️ **때리는 힘은 그 역할에 맞는 쪽을 쓴다.** 원거리는 특수공격, 나머지는 물리공격.
   *    후딘(물리 50 · 특수 135)을 근접으로 쓰면 약골이 되고, 괴력몬(130 · 65)을 원거리로
   *    쓰면 헛것이 된다 — 원작이 이미 나눠 놓은 것을 그대로 따른다.
   */
  const 때림 = 역 === '원거리' ? p.특공 : p.공;
  /**
   * ⚠️ **비싼 탱커는 공격도 붙는다**(사장님 2026-08-17: "비싼 탱커는 몸이 엄청 더 좋거나
   *    공격도 괜찮은거"). 종족값 총합 400을 넘는 만큼 공격 배수를 최대 1.6배까지 올린다 —
   *    잠만보(540)가 데구리(390)와 공격이 비슷하던 것을 바로잡는다.
   */
  const 큰탱커 = 역 === '탱커' ? Math.min(1.6, 1 + Math.max(0, p.총합 - 400) / 250) : 1;
  return {
    id, ko: p.ko, 타입: p.타입, 역할: 역, 값, 쿨,
    hp: Math.round(p.hp * 4.0 * b.hp * 세기),
    공: Math.round(때림 * 0.55 * b.공 * 큰탱커 * 세기),
    사거리: b.사거리,
    // ⚠️ **속도에 바닥을 둔다.** 잠만보(속 30)를 그대로 쓰면 기어가서 전장에 영영 못 닿는다.
    속도: Math.round((26 + p.속 * 0.45) * b.속도),
    간격: Number((b.간격).toFixed(2)),
  };
}

