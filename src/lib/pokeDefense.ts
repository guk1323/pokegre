/**
 * 때리는 쪽 타입들 → 맞는 쪽 타입들에 대한 배수.
 * ⚠️ 맞는 쪽이 두 타입이면 **곱한다**(리자몽=불꽃·비행이라 바위에 4배로 맞는다).
 * ⚠️ 때리는 쪽이 두 타입이면 **유리한 쪽을 쓴다** — 게임에서 기술을 고르는 셈이다.
 */
export function 상성배수(때리는: string[], 맞는: string[]): number {
  // ⚠️⚠️ **`|| 1`로 넘기면 안 된다.** 처음에 `return 제일 || 1`로 뒀더니 **무효(0배)가
  //    1배로 되살아났다** — 전기가 땅에, 노말이 고스트에 그대로 먹혔다(2026-08-16 검사에서
  //    잡음). 0은 「자료가 없다」가 아니라 **「안 통한다」는 답**이다.
  //    자료가 없을 때만(때리는 쪽이 비었을 때) 1로 둔다.
  if (!때리는.length) return 1;
  let 제일 = 0;
  for (const a of 때리는) {
    let 곱 = 1;
    for (const d of 맞는) 곱 *= 상성표[a]?.[d] ?? 1;
    제일 = Math.max(제일, 곱);
  }
  return 제일;
}

