/**
 * 값 그래프의 **오름폭(▲ %)**을 낸다. **두 그래프가 이 한 벌만 쓴다**
 * (이베이 등급별 그래프 · 스니커덩크 실거래 그래프).
 *
 * ⚠️⚠️ **첫 점과 끝 점 하나씩으로 세면 안 된다.** 그 하루에 싸게 팔린 한 건이 그대로
 *    전체 오름폭이 된다 — 베이스셋 리자몽 psa10이 "▲4525%"($400 → $18,500)로 나가고
 *    있었다(2026-08-08 실측). 등급칸 486개 중 18개(3.7%)가 300%를 넘었다.
 *    **앞 세 점과 뒤 세 점의 중앙값**으로 견주면 7개로 줄고 최악이 사라진다.
 * ⚠️ 점이 여섯 개도 안 되면 **아예 안 낸다**(null). 넉 점짜리로 "▲2300%"라고 적는 건
 *    아는 척이다. 그래프 자체는 그대로 그린다.
 * ⚠️ 규칙을 화면마다 따로 적지 않는다 — 실제로 두 그래프가 각자 적어 두고 있었고,
 *    한쪽만 고치면 같은 자료가 화면마다 다르게 보인다(2026-08-08에 여러 번 겪었다).
 */
const 중앙 = (v: number[]): number => {
  const a = [...v].sort((x, y) => x - y);
  return a.length % 2 ? a[(a.length - 1) / 2] : (a[a.length / 2 - 1] + a[a.length / 2]) / 2;
};

export function 오름폭(prices: number[]): number | null {
  if (prices.length < 6) return null;
  const 앞 = 중앙(prices.slice(0, 3));
  const 뒤 = 중앙(prices.slice(-3));
  if (!(앞 > 0)) return null;
  return ((뒤 - 앞) / 앞) * 100;
}
