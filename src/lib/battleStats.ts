// 대전쟁 통계 줄을 읽고 모으는 셈. **화면에서 떼어 놓았다.**
//
// ⚠️⚠️ 왜 떼었나: 통계 화면(`VisitStats`)은 **운영자로 로그인해야** 서버가 자료를 준다.
//    그래서 로컬에서 눈으로 확인할 수가 없고, 셈이 맞는지도 확인이 안 됐다.
//    셈만 떼어 놓으면 `npx tsx scripts/check-battle-stats.mts`로 **로그인 없이** 검증된다.
//
// ⚠️⚠️⚠️ **줄 하나가 두 가지 꼴이다.**
//    2026-08-18부터 난이도를 넣어 `판 · 난이도 · 무엇` **세 칸**으로 오는데,
//    그 전에 쌓인 것은 `판 · 무엇` **두 칸**이다. 두 칸짜리를 버리면 그때까지 쌓인 기록이
//    화면에서 통째로 사라진다 — 난이도만 모르는 것으로 두고 판 표에는 그대로 더한다.

export interface 전투줄 {
  name: string;
  count: number;
}
export interface 전투칸 {
  시작: number;
  깸: number;
  짐: number;
  /**
   * **시작해 놓고 끝을 안 본 판.** 이겨서도 져서도 아니고 그냥 나간 것이다.
   * ⚠️⚠️ 이게 없으면 「시작 100 · 깸 40 · 짐 20」에서 **남은 40이 어디 갔는지** 알 수 없다.
   *    깬 비율만 보면 그 40이 「어려워서 진 것」처럼 읽히는데, 실제로는 **지겨워서 나간 것**일 수 있다.
   */
  그만둠: number;
}

/**
 * **왜 졌나** 줄에 붙는 머리.
 *
 * ⚠️⚠️ ' · '가 한 번도 없어야 한다 — 그래야 `전투줄읽기`가 null을 내고 판별·난이도별
 *    표에 **빈 줄이 끼지 않는다**. 이 머리를 「짐까닭 · …」으로 바꾸면 판 이름이
 *    「짐까닭」인 유령 줄이 판별 표에 생긴다.
 */
export const 까닭머리 = '짐까닭:';

/** 「1. 1번도로 · 어려움 · 깸」 또는 옛 꼴 「1. 1번도로 · 깸」을 뜯는다. */
export function 전투줄읽기(이름: string): { 판: string; 난: string | null; 무엇: string } | null {
  // 왜 졌나 줄은 판·난이도 표의 것이 아니다.
  if (이름.startsWith(까닭머리)) return null;
  const 칸 = 이름.split(' · ');
  // ⚠️ 3칸보다 많으면 **판 이름에 「 · 」가 든 것**이다. 뒤에서부터 세어야 안 밀린다.
  if (칸.length >= 3) {
    return { 판: 칸.slice(0, -2).join(' · '), 난: 칸[칸.length - 2], 무엇: 칸[칸.length - 1] };
  }
  if (칸.length === 2) return { 판: 칸[0], 난: null, 무엇: 칸[1] };
  return null;
}

function 더하기(칸: 전투칸, 무엇: string, n: number) {
  if (무엇 === '시작') 칸.시작 += n;
  else if (무엇 === '깸') 칸.깸 += n;
  else if (무엇 === '짐') 칸.짐 += n;
  else if (무엇 === '그만둠') 칸.그만둠 += n;
  // ⚠️ 모르는 말은 **그냥 버린다.** 아무 칸에나 더하면 옛 기록이 조용히 틀어진다.
}

/** 스테이지마다 시작·깸·짐을 모은다. **판 번호 차례**로 세운다(여정 순서). */
export function 판별모으기(줄들: 전투줄[]): ({ 판: string } & 전투칸)[] {
  const m = new Map<string, 전투칸>();
  for (const x of 줄들) {
    const r = 전투줄읽기(x.name);
    if (!r) continue;
    const 칸 = m.get(r.판) ?? { 시작: 0, 깸: 0, 짐: 0, 그만둠: 0 };
    더하기(칸, r.무엇, x.count);
    m.set(r.판, 칸);
  }
  return [...m]
    .map(([판, v]) => ({ 판, ...v }))
    // ⚠️ 많이 한 순으로 세우면 여정 순서가 흐트러져 「어디서 막히나」가 안 보인다.
    .sort((a, b) => (parseInt(a.판, 10) || 99) - (parseInt(b.판, 10) || 99));
}

/** 난이도 넣기 전 기록이 들어가는 칸. 아무 난이도에 몰아넣으면 거짓이 된다. */
export const 옛기록칸 = '(난이도 넣기 전)';
const 난이도차례 = ['쉬움', '보통', '어려움', 옛기록칸];

/**
 * 난이도마다 시작·깸·짐을 모은다.
 * ⚠️ **별을 난이도가 주므로 이 축이 없으면 별이 잘 갈리는지 알 수 없다.**
 */
export function 난이도별모으기(줄들: 전투줄[]): ({ 난: string } & 전투칸)[] {
  const m = new Map<string, 전투칸>();
  for (const x of 줄들) {
    const r = 전투줄읽기(x.name);
    if (!r) continue;
    const 열쇠 = r.난 ?? 옛기록칸;
    const 칸 = m.get(열쇠) ?? { 시작: 0, 깸: 0, 짐: 0, 그만둠: 0 };
    더하기(칸, r.무엇, x.count);
    m.set(열쇠, 칸);
  }
  return [...m]
    .map(([난, v]) => ({ 난, ...v }))
    .sort((a, b) => 난이도차례.indexOf(a.난) - 난이도차례.indexOf(b.난));
}

/**
 * 열쇠 → 사람이 읽는 말. **`진까닭`이 고르는 차례대로** 적어 둔다(위가 더 크게 잘못된 것).
 * ⚠️ 모르는 열쇠는 **그대로 보여 준다** — 버리면 새로 만든 까닭이 조용히 사라진다.
 */
const 까닭이름: Record<string, string> = {
  벽없음: '벽을 안 냈다',
  상성: '상성이 밀렸다',
  빈손: '무리를 빈손으로 맞았다',
  지갑넘침: '지갑이 꽉 찬 채로 뒀다',
  원거리없음: '원거리를 안 냈다',
  난이도: '조금 모자랐다(난이도 낮추기 권함)',
  모아내기: '조금 모자랐다(모아 내기 권함)',
};

/**
 * **왜 졌나**를 까닭마다 모은다. 많은 것부터 세운다.
 *
 * ⚠️⚠️ 이 표가 있어야 「어느 판이 어렵나」에서 **「무엇을 몰라서 지나」**로 넘어간다.
 *    벽을 안 내서 지는 사람이 많으면 판을 쉽게 할 일이 아니라 **하는 법을 고칠 일**이다.
 */
export function 까닭모으기(줄들: 전투줄[]): { 까닭: string; 수: number }[] {
  const m = new Map<string, number>();
  for (const x of 줄들) {
    if (!x.name.startsWith(까닭머리)) continue;
    const 열쇠 = x.name.slice(까닭머리.length);
    const 이름 = 까닭이름[열쇠] ?? 열쇠;
    m.set(이름, (m.get(이름) ?? 0) + x.count);
  }
  return [...m].map(([까닭, 수]) => ({ 까닭, 수 })).sort((a, b) => b.수 - a.수);
}
