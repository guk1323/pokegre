  //    한 장 칸에 들어 있었다). 「sequential」은 묶음 감정에만 쓰는 말이라 좁게 안전하다.
  // ⚠️ **제 이름이 「[Set of 4]」인 카드는 예외다** — V-UNION은 넉 장이 모여 한 장 구실을 해서
