  // ② 언어판 — 우리 판과 다른 언어가 적혀 있으면 「기타 언어」 곁 카드로 보낸다.
  //    ⚠️ 일본판 카드(ja-)에 「Japanese」는 맞는 말이므로 안 건다. 중국판 카드(zh-)도 마찬가지.
  //    ⚠️ **영문 카드에 적힌 「일본판」만은 기타 언어가 아니라 뺀다** — 일본판은 우리 도감에
  //       제 카드가 따로 있어서, 기타 언어에 담으면 같은 낙찰이 두 카드에 실린다.
  // ①-2 여러 장 묶음 — 감정 번호가 이어지는 세트로 파는 매물(「PSA 10 Sequential Set -
