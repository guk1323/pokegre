  // ⚠️ 「금속 카드」가 **제 상품인 카드**(151 Metal Card 등)는 예외다 — 이 말이 곧 그 카드다
  //    (2026-08-25 · 쌍둥이표 작업에서 발견. 안 뚫으면 그 카드의 낙찰이 통째로 지워진다).
