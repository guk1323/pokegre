/**
 * 도감 카드 이름의 괄호 표시(「(포켓몬센터 한정)」·「(Eevee Stamped)」·「(EBGames 한정)」)에서
 * 제목에 나올 도장 말을 뽑는다. 서버가 도장판 쌍둥이의 표시를 넣어 `판정카드.도장쌍둥이`를 만든다.
 * ⚠️ 너무 넓게 잡지 않는다 — 「Pokemon Center」는 출처 설명으로도 흔히 적히지만, 쌍둥이가
 *    실제로 있는 카드에서만 이 말이 들어오므로 여기서는 그 카드 것으로 본다.
 */
export function 도장말뽑기(표시: string): RegExp[] {
  const 말: RegExp[] = []
  const 피 = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  if (/pok[eé]mon\s*center|포켓몬\s*센터/i.test(표시)) 말.push(/pok[eé]mon\s*center|\bPC\s*(?:stamp|exclusive|promo)\b/i)
  if (/EB\s*Games|EBGames/i.test(표시)) 말.push(/\beb\s*games\b/i)
  if (/gamestop/i.test(표시)) 말.push(/\bgamestop\b/i)
  if (/showcase/i.test(표시)) 말.push(/\bshowcase\b/i)
  if (/costco/i.test(표시)) 말.push(/\bcostco\b/i)
  const st = 표시.match(/([A-Za-z0-9# ]+?)\s*stamp(?:ed)?\b/i)
  if (st) {
    const w = st[1].trim().replace(/^#\d+\s*/, '').trim()
    // 「Eevee Stamped」 → 「eevee … stamp」, 「#16 Pikachu Stamped」 → 「pikachu … stamp」
    말.push(w ? new RegExp(`${피(w)}[^|]{0,12}stamp`, 'i') : /\bstamp(?:ed)?\b/i)
  }
  if (!말.length && /stamp/i.test(표시)) 말.push(/\bstamp(?:ed)?\b/i)
  return 말
}

export function 제목언어이름(t: string): string {
  const s = String(t || '')
  for (const [re, 이름] of 중국말) if (re.test(s)) return 이름.replace(/\(.*$/, '')
  for (const [re, 이름] of 딴나라말) if (re.test(s)) return 이름.replace(/\(.*$/, '')
  return ''
}

