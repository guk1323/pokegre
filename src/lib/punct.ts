// 전각 부호(＆！？：（）)를 보통 부호로. **이름·검색어를 다루는 곳이 이 한 벌만 쓴다.**
//
// 왜 필요한가: 일본 카드 이름에는 전각 부호가 섞여 있다(「ナツメ＆ハチク」→「초련＆담죽」).
// 그런데 우리 사전과 검색어 대조는 보통 부호로 적혀 있어서, **한 글자 때문에 통째로
// 안 맞는다.**
//   · 영어 번역:  "초련＆담죽"은 그대로 남고 "초련&담죽"만 "Sabrina & Brycen"이 된다
//   · 인기 검색어: 둘이 다른 말로 세어져 한 카드의 표가 두 줄로 갈린다
// 사람들은 화면에 보이는 이름을 그대로 복사해 붙여 넣으므로 두 형태가 다 들어온다.
// (2026-08-07 점검에서 확인)
//
// ⚠️ 한글이 하나도 없는 이름(번역 안 된 일본어 원문)에는 쓰지 말 것 — 그쪽은 전각이
//    맞는 표기다. 그 판단은 부르는 쪽에서 한다(koCardName의 부호다듬기 참고).
// ⚠️ 이 파일은 **아무것도 가져오지 않는다.** 서버가 koCardName을 거쳐 쓰기 때문이다.
//    Dockerfile COPY 목록에도 있어야 한다(`npm run build`가 빠뜨리면 알려 준다).

export const 전각부호펴기 = (s: string): string =>
  s
    .replace(/＆/g, '&')
    .replace(/！/g, '!')
    .replace(/？/g, '?')
    .replace(/：/g, ':')
    .replace(/（/g, '(')
    .replace(/）/g, ')');
