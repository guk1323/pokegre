// 쪽 나누기에 쓰는 셈. 게시판 목록과 오늘의 상점 GP 내역이 같이 쓴다.
//
// ⚠️ 게시판 안에만 있던 것을 떼어 냈다(2026-08-29). 두 군데가 각자 가지고 있으면
//    한쪽만 고쳐 서로 다르게 움직인다 — 이 리포에서 이미 여러 번 겪은 일이다.

/**
 * 쪽 번호로 무엇을 보여 줄지. 쪽이 30개면 번호를 30개 그릴 수 없으니 지금 쪽 둘레만 낸다.
 * 앞뒤로 두 개씩(기본 최대 5개) — 네이버 카페도 이런 식이다.
 */
export function 쪽번호들(지금: number, 전체: number, 최대 = 5): number[] {
  if (전체 <= 최대) return Array.from({ length: 전체 }, (_, i) => i + 1);
  // 끝쪽에 붙으면 창을 안쪽으로 밀어, 늘 최대 개수가 보이게 한다.
  const 시작 = Math.min(Math.max(1, 지금 - Math.floor(최대 / 2)), 전체 - 최대 + 1);
  return Array.from({ length: 최대 }, (_, i) => 시작 + i);
}
