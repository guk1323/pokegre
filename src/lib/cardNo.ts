/**
 * 카드 번호를 **열쇠로 쓸 꼴**로 다듬는다. 서버와 화면이 이 한 벌만 쓴다.
 *
 * ⚠️⚠️ **번호를 Number()로 바꾸면 안 된다.** 이게 여러 곳에 퍼져 있었다
 *    (2026-08-08에 찾음). 카드 번호는 숫자가 아닌 것이 많다 —
 *        RC1~RC32(래디언트 컬렉션) · TG01(트레이너 갤러리) · GG01(갈라르 갤러리)
 *        SWSH001(프로모) · CC001(클래식 컬렉션) · 24a(대체 아트) · 232/XY-P
 *    `Number("RC5")`는 NaN이라, **그런 카드가 전부 "NaN" 한 칸에 뭉친다.**
 *    우리 카드 40,489장 중 **1,864장이 41개 세트에서 그렇게 뭉치고 있었다.**
 *    결과가 눈에 보였다 — 세트 화면에서 값 있는 카드 하나의 값이 그 세트의
 *    번호가 숫자가 아닌 카드 **전부**에 붙어 나갔다(en-g1의 RC 34장이 같은 값).
 *
 * 하는 일은 **앞의 0을 떼는 것뿐**이다("024" = "24"). 서버의 stripZeros와 같다 —
 * 한쪽만 바꾸면 값이 안 붙으므로 규칙이 어긋나면 안 된다.
 */
export const 번호열쇠 = (n: unknown): string => String(n ?? '').trim().replace(/^0+(?=.)/, '')
