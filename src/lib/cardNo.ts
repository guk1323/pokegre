/**
 * 카드 번호를 **열쇠로 쓸 꼴**로 다듬는다. 서버와 화면이 이 한 벌만 쓴다.
 *
 * ⚠️⚠️ **번호를 Number()로 바꾸면 안 된다.** 이게 여러 곳에 퍼져 있었다
 *    (2026-08-08에 찾음). 카드 번호는 숫자가 아닌 것이 많다 —
 *        RC1~RC32(래디언트 컬렉션) · TG01(트레이너 갤러리) · GG01(갈라르 갤러리)
 *        SWSH001(프로모) · CC001(클래식 컬렉션) · 24a(대체 아트) · 232/XY-P
 *    `Number("RC5")`는 NaN이라, **그런 카드가 전부 "NaN" 한 칸에 뭉친다.**
 *    우리 카드 40,489장 중 **1,864장이 41개 세트에서 그렇게 뭉치고 있었다.**
 *    결과가 눈에 보였다 — 세트 화면에서 **값 있는 카드 하나의 값이 그 세트의 번호가
 *    숫자가 아닌 카드 전부에 붙어** 나갔다. 배포 전 실측으로 **20개 세트 1,480장**이
 *    그랬다:
 *        en-swshp   프로모 302장이 전부 $430.76 하나로
 *        en-smp     248장이 전부 $489.99 · en-xyp 216장이 전부 $423.88
 *        en-sma     샤이니볼트 94장이 전부 $195.04
 *        en-swsh12.5gg 갈라르갤러리 70장이 전부 $138.19
 *    값 있는 카드의 번호가 숫자면(en-g1) 값이 안 붙는 쪽으로 틀렸다.
 *
 * 하는 일은 **앞의 0을 떼는 것뿐**이다("024" = "24"). 서버의 stripZeros와 같다 —
 * 한쪽만 바꾸면 값이 안 붙으므로 규칙이 어긋나면 안 된다.
 */
export const 번호열쇠 = (n: unknown): string => String(n ?? '').trim().replace(/^0+(?=.)/, '')

/**
 * 앨범 카드 하나의 값을 시세표에서 꺼낸다. **화면과 서버가 이 한 벌만 쓴다.**
 *
 * ⚠️ 예전엔 같은 코드가 세 군데 있었다(카드 뽑기 화면 · 앨범 값 매기기 · 홈 통계).
 *    지금은 세 곳이 같은 답을 내지만, 규칙이 셋이면 언젠가 한쪽만 고쳐 **같은 카드가
 *    화면마다 다른 값**을 갖는다 — 2026-08-08 하루에만 그 사고를 네 번 봤다.
 *
 * 변형판(마스터볼·몬스터볼·리버스)은 별도 열쇠로 담겨 있다. 변형판 값이 없으면
 * 기본판 값으로 떨어진다.
 */
export const 앨범값 = (
  시세: Record<string, number> | undefined,
  번호: unknown,
  변형?: string | null,
): number => {
  if (!시세) return 0
  const base = 번호열쇠(번호)
  const vk = 변형 === 'master' ? '~m' : 변형 === 'poke' ? '~p' : 변형 === 'rev' ? '~r' : ''
  return (vk ? 시세[base + vk] : undefined) ?? 시세[base] ?? 0
}

/**
 * 화면에 **보여 줄** 카드 번호. 속에 저장된 열쇠는 그대로 두고 표시만 짧게 한다.
 *
 * 왜 — 저쪽이 한 세트에 서로 다른 카드를 같은 번호로 넣어 두는 곳이 있어, 우리는 구분표를
 * 붙여 갈라 뒀다(`119~#21Charizard.156`). 열쇠로는 옳지만 **읽을 수 없다.**
 *   `119~#21Charizard.156` → `#21`   그 상품에서의 번호가 사람에게 제일 뜻이 있다
 *   `109~Pikachu47`        → `47`
 *   `58~RedCheeks.102`     → `58`
 * ⚠️ **열쇠로 쓰지 말 것.** 이건 눈에 보여 줄 때만 쓴다 — 짧게 만드느라 겹칠 수 있다.
 */
export const 보일번호 = (n: unknown): string => {
  const s = String(n ?? '').trim()
  const i = s.indexOf('~')
  // ⚠️⚠️ **`#123456`은 카드 번호가 아니다 — 우리가 지어낸 자리표다.** PPT가 번호를 안 주는
  //    세트가 있어서 칸을 비울 수 없어 PPT 번호(tcgPlayerId)를 그대로 넣어 뒀다(3,443장).
  //    화면에 그대로 내면 방문자에겐 뜻 없는 여섯 자리다 — "1996-10 · #577000"
  //    (2026-08-09 사장님 지적). **감춘다.** 자료에는 그대로 둔다 — 카드를 가리키는
  //    열쇠라 지우면 시세를 못 찾는다.
  // ⚠️ `19~#55Pikachu`의 `#55`는 **카드에 실제로 찍힌 스탬프 번호**라 감추면 안 된다.
  //    그래서 `~`가 없이 `#`로 시작하는 것만 감춘다.
  if (i < 0 && /^#\d+$/.test(s)) return ''
  if (i < 0) return s
  const 앞 = s.slice(0, i)
  const 뒤 = s.slice(i + 1)
  const 속 = /^#(\d+)/.exec(뒤)
  if (속) return '#' + 속[1]
  const 덱 = /^[A-Za-z]+(\d+)/.exec(뒤)
  if (덱) return 덱[1]
  return 앞
}

/**
 * **이 세트가 일본 쪽 것인가**(일본판 + 중국판).
 *
 * ⚠️⚠️ **왜 한 벌로 두는가:** 세트 슬러그 앞머리로 판을 가르는 자리가 **일곱 곳**인데
 *    전부 「`ja-`가 아니면 영문판」이었다. 중국판 세트(`zh-`)를 들이면서 한 곳만 놓치면
 *    **오류 없이 조용히 영문판으로 흘러간다** — PPT를 영문으로 물어 0건이 오고, 화면은
 *    「그런 카드 없음」이 된다. 규칙이 일곱 벌이면 언젠가 반드시 어긋난다.
 *
 * ⚠️ **중국판을 일본 쪽으로 보는 것은 사실에 맞다.** 중국판 카드는 PPT의 **japanese**
 *    목록에 들어 있고(영문 목록엔 없다), 거래도 스니커덩크(일본 마켓)에서 일어난다.
 * ⚠️ **화면의 판 토글은 그대로 둘(일본판·영문판)이다**(사장님 결정 2026-08-18).
 *    중국판 카드는 **일본판 목록에 섞여 보이고 이름에만 「(중국판)」**을 단다.
 *    `zh-`는 화면에 드러나는 판이 아니라 **속으로 쓰는 표식**이다 —
 *    중국판 낙찰 거르기(`중국판낙찰`)가 「내 카드가 중국판인지」를 이걸로 안다.
 */
export const 일본쪽세트 = (slug: unknown): boolean => {
  const s = String(slug ?? '')
  // ⚠️ **한국판(`ko-`)도 일본 쪽으로 본다** — 중국판과 같은 까닭이다(2026-09-04).
  //    한국 전용 프로모는 **PPT에 상품 자체가 없고**(검색 0건 실측), 실제 거래는
  //    스니커덩크에서 일어난다. 영문판으로 흘려보내면 있지도 않은 TCGplayer를 묻게 된다.
  return s.startsWith('ja-') || s.startsWith('zh-') || s.startsWith('ko-')
}

/**
 * 세트 딱지에 **적을 판 이름**. 세트의 `ed`는 ja/en 둘뿐이라 그것만 보면
 * **중국어판·한국어판이 「일본어판」으로 붙는다**(2026-09-04에 잡음 — 중국판 세트가
 * 그렇게 나가고 있었다). 슬러그 앞머리가 실제 판이므로 그것을 먼저 본다.
 */
export const 판이름 = (slug: unknown, ed: unknown): string => {
  const s = String(slug ?? '')
  if (s.startsWith('zh-')) return '중국어판'
  if (s.startsWith('ko-')) return '한국어판'
  return ed === 'ja' ? '일본어판' : '영문판'
}

/** 이 세트가 중국판인가. 낙찰 거르기의 안전장치가 쓴다. */
export const 중국판세트 = (slug: unknown): boolean => String(slug ?? '').startsWith('zh-')

/**
 * 카드 번호를 **사람이 세는 차례**로 줄 세우는 열쇠.
 *
 * ⚠️⚠️ 글자로 견주면 안 된다 — "10"이 "2"보다 앞에 온다. 그렇다고 `Number()`로
 *    바꿔도 안 된다(위 `번호열쇠` 주석 참고 — RC5·TG01·SWSH001이 전부 NaN 한 칸에 뭉친다).
 *    그래서 **글자 머리 + 숫자 + 나머지**로 쪼개서 견준다.
 *        "13"      → 머리 ''    숫자 13
 *        "RC5"     → 머리 'RC'  숫자 5
 *        "SWSH001" → 머리 'SWSH' 숫자 1
 *        "24a"     → 머리 ''    숫자 24  나머지 'a'
 *        "12~568512" → `~` 앞(12)으로 견주고, 같으면 원문으로 가른다
 *
 * 차례: ① 번호다운 것 → ② 숫자가 아예 없는 것 → ③ 자리표(#숫자)
 *    ③은 저쪽이 번호를 안 줘서 우리가 PPT 번호를 넣어 둔 것이라(3,443장) 뜻이 없다.
 *    화면에도 안 보이므로(`보일번호`) 맨 뒤로 보낸다.
 * 머리가 빈 것('')이 먼저 온다 — 본편 번호가 앞, RC·TG 같은 딸림 묶음이 뒤다.
 */
export function 번호차례(n: unknown): [number, string, number, string] {
  const s = String(n ?? '').trim()
  const base = s.split('~')[0]
  if (/^#[0-9]+$/.test(base)) return [2, '', Number(base.slice(1)), s]
  const m = /^([A-Za-z]*)([0-9]+)(.*)$/.exec(base)
  if (m) return [0, m[1].toUpperCase(), Number(m[2]), m[3] + '|' + s]
  return [1, base.toUpperCase(), 0, s]
}

/** `번호차례`로 두 카드 번호를 견준다. `sort`에 그대로 넣는다. */
export function 번호비교(a: unknown, b: unknown): number {
  const x = 번호차례(a)
  const y = 번호차례(b)
  return x[0] - y[0] || x[1].localeCompare(y[1]) || x[2] - y[2] || x[3].localeCompare(y[3])
}
