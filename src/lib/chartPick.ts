/**
 * 그래프에서 **마우스가 가리키는 점**을 고른다. 두 그래프(스니커덩크·이베이)가 한 벌만 쓴다.
 *
 * ⚠️⚠️ **점은 날짜 간격으로 놓인다 — 개수로 나누면 어긋난다.**
 *    x자리는 `((그날 - 처음날) / (마지막날 - 처음날)) * 너비`로 정해진다. 그래서 거래가
 *    몰린 날은 점이 촘촘하고, 비는 기간은 점 사이가 넓다.
 *    예전엔 커서를 이렇게 찾았다 —
 *      번호 = 반올림( (커서x / 너비) * (점개수 - 1) )
 *    이건 **점이 고르게 놓였다고 가정한 셈**이라, 띄엄띄엄한 카드에서는 커서가 가리키는
 *    자리와 세로선이 눈에 띄게 밀렸다(사장님 지적 2026-08-29: 「내 커서 위치를 보여주는 게
 *    아니라 살짝 밀려서 보여준다」).
 *    → **가로자리(cx)가 제일 가까운 점**을 고른다. 그러면 세로선이 늘 커서 밑에 선다.
 *
 * @param 점들 그려 둔 점들(`cx`는 뷰박스 기준 가로자리)
 * @param 커서x 커서의 가로자리 — **뷰박스 기준**으로 바꿔서 넘긴다
 */
export function 가까운점(점들: { cx: number }[], 커서x: number): number {
  if (!점들.length) return 0;
  let 고른것 = 0;
  let 제일가까움 = Infinity;
  for (let i = 0; i < 점들.length; i++) {
    const 거리 = Math.abs(점들[i].cx - 커서x);
    // ⚠️ `<`로 둔다(`<=` 아님) — 같은 자리에 점이 겹치면 **먼저 온 것**(옛 날짜)을 남긴다.
    if (거리 < 제일가까움) {
      제일가까움 = 거리;
      고른것 = i;
    }
  }
  return 고른것;
}
